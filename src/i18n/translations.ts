export function isLocale(value: unknown): value is Locale {
  return value === 'id' || value === 'en' || value === 'ar';
}
export function tr(key: string, language: Locale): string {
  if (language === 'id') return key;
  const translated = (language === 'ar' ? ar : en)[key];
  return translated || key;
}
export function localeIntl(language: Locale): string {
  return language === 'ar' ? 'ar' : language === 'en' ? 'en-GB' : 'id-ID';
}

/** Locale-aware display only; ISO date keys and persisted week selection are unchanged. */
export function displaySchoolWeekRange(mondayISO: string, fridayISO: string, language: Locale): string {
  const date = (iso: string): Date => {
    const match = /^(\d{4})-(\d{2})-(\d{2})$/.exec(iso);
    if (!match) return new Date(NaN);
    return new Date(Number(match[1]), Number(match[2]) - 1, Number(match[3]));
  };
  const monday = date(mondayISO);
  const friday = date(fridayISO);
  if (Number.isNaN(monday.getTime()) || Number.isNaN(friday.getTime())) return `${mondayISO} – ${fridayISO}`;
  const locale = localeIntl(language);
  const short = new Intl.DateTimeFormat(locale, { day: 'numeric', month: 'short' });
  const full = new Intl.DateTimeFormat(locale, { day: 'numeric', month: 'short', year: 'numeric' });
  return `${short.format(monday)} – ${full.format(friday)}`;
}
