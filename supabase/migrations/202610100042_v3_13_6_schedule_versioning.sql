begin;

-- E-Jadwal V3.13.6 — Schedule Versioning / Publish History / Rollback
-- Captures the canonical schedule state after schedule-changing audit events.
-- One database transaction = one schedule version, so combined sessions and
-- batch imports do not produce dozens of partial versions.

create table if not exists public.schedule_versions (
  id uuid primary key default gen_random_uuid(),
  version_no bigint generated by default as identity unique,
  txid bigint not null unique,
  source_action text not null,
  source_entity_type text null,
  source_entity_id text null,
  actor_user_id uuid null references auth.users(id) on delete set null,
  metadata jsonb not null default '{}'::jsonb,
  snapshot jsonb not null,
  created_at timestamptz not null default now()
);

create index if not exists schedule_versions_created_at_idx
  on public.schedule_versions (created_at desc);

alter table public.schedule_versions enable row level security;

drop policy if exists schedule_versions_staff_read on public.schedule_versions;
create policy schedule_versions_staff_read
on public.schedule_versions
for select
to authenticated
using (public.current_user_is_staff());

-- Canonical snapshot. It intentionally versions only schedule-affecting data:
-- recurring master, master teachers, incidentals, incidental teacher overrides,
-- and academic calendar events. Leave/badal/task workflow is operational history
-- and must never be rewound by schedule rollback.
create or replace function public.ejadwal_schedule_snapshot_v1()
returns jsonb
language sql
security definer
set search_path = public, pg_temp
as $$
  select jsonb_build_object(
    'schema_version', 1,
    'captured_at', now(),
    'schedule_master', coalesce((
      select jsonb_agg(to_jsonb(sm) order by sm.id)
      from public.schedule_master sm
    ), '[]'::jsonb),
    'schedule_master_teachers', coalesce((
      select jsonb_agg(to_jsonb(smt) order by smt.schedule_id, smt.position)
      from public.schedule_master_teachers smt
    ), '[]'::jsonb),
    'schedule_incidentals', coalesce((
      select jsonb_agg(to_jsonb(si) order by si.id)
      from public.schedule_incidentals si
    ), '[]'::jsonb),
    'schedule_incidental_teacher_overrides', coalesce((
      select jsonb_agg(to_jsonb(ito) order by ito.incidental_id, ito.position)
      from public.schedule_incidental_teacher_overrides ito
    ), '[]'::jsonb),
    'academic_events', coalesce((
      select jsonb_agg(to_jsonb(ae) order by ae.id)
      from public.academic_events ae
    ), '[]'::jsonb)
  );
$$;

revoke all on function public.ejadwal_schedule_snapshot_v1() from public;

create or replace function public.ejadwal_capture_schedule_version_from_audit_v1()
returns trigger
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_txid bigint := txid_current();
  v_relevant boolean := false;
  v_metadata jsonb;
begin
  v_relevant := new.action in (
    'SCHEDULE_MASTER_QUICK_EDIT',
    'SCHEDULE_INCIDENTAL_INSERT',
    'SCHEDULE_INCIDENTAL_UPDATE',
    'SCHEDULE_INCIDENTAL_DELETE',
    'SCHEDULE_IMPORT_PUBLISH',
    'SYAIKH_ROTATION_IMPORT_PUBLISH',
    'SCHEDULE_VERSION_ROLLBACK'
  ) or (
    new.action like 'OPERATIONAL_RULE_%'
    and upper(coalesce(new.entity_type, '')) = 'ACADEMIC_EVENTS'
  );

  if not v_relevant then
    return new;
  end if;

  v_metadata := jsonb_build_object(
    'audit_id', new.id,
    'request_id', new.request_id,
    'before_data', new.before_data,
    'after_data', new.after_data
  );

  insert into public.schedule_versions(
    txid,
    source_action,
    source_entity_type,
    source_entity_id,
    actor_user_id,
    metadata,
    snapshot,
    created_at
  ) values (
    v_txid,
    new.action,
    new.entity_type,
    new.entity_id,
    new.actor_user_id,
    v_metadata,
    public.ejadwal_schedule_snapshot_v1(),
    new.created_at
  )
  on conflict (txid) do update
    set source_action = excluded.source_action,
        source_entity_type = excluded.source_entity_type,
        source_entity_id = excluded.source_entity_id,
        actor_user_id = coalesce(excluded.actor_user_id, public.schedule_versions.actor_user_id),
        metadata = excluded.metadata,
        snapshot = excluded.snapshot,
        created_at = excluded.created_at;

  return new;
end;
$$;

revoke all on function public.ejadwal_capture_schedule_version_from_audit_v1() from public;

drop trigger if exists capture_schedule_version_from_audit on public.audit_logs;
create trigger capture_schedule_version_from_audit
after insert on public.audit_logs
for each row execute function public.ejadwal_capture_schedule_version_from_audit_v1();

-- Avoid flooding audit_logs while a rollback restores academic_events row-by-row.
-- The rollback writes one explicit SCHEDULE_VERSION_ROLLBACK event at the end.
create or replace function public.ejadwal_audit_operational_rule_change()
returns trigger
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_entity_id text;
  v_before jsonb;
  v_after jsonb;
begin
  if current_setting('ejadwal.rollback_mode', true) = 'on' then
    if tg_op = 'DELETE' then return old; end if;
    return new;
  end if;

  if tg_op = 'INSERT' then
    v_entity_id := coalesce(to_jsonb(new)->>'id', '');
    v_before := null;
    v_after := to_jsonb(new);
  elsif tg_op = 'UPDATE' then
    v_entity_id := coalesce(to_jsonb(new)->>'id', to_jsonb(old)->>'id', '');
    v_before := to_jsonb(old);
    v_after := to_jsonb(new);
  else
    v_entity_id := coalesce(to_jsonb(old)->>'id', '');
    v_before := to_jsonb(old);
    v_after := null;
  end if;

  insert into public.audit_logs(
    actor_user_id, action, entity_type, entity_id, before_data, after_data
  ) values (
    auth.uid(), 'OPERATIONAL_RULE_' || tg_op, upper(tg_table_name), v_entity_id, v_before, v_after
  );

  if tg_op = 'DELETE' then return old; end if;
  return new;
end;
$$;

revoke all on function public.ejadwal_audit_operational_rule_change() from public;

create or replace function public.ejadwal_list_schedule_versions_v1(p_limit integer default 50)
returns table(
  version_id uuid,
  version_no bigint,
  source_action text,
  source_entity_type text,
  source_entity_id text,
  actor_user_id uuid,
  actor_label text,
  metadata jsonb,
  master_count integer,
  active_incidental_count integer,
  active_calendar_count integer,
  created_at timestamptz
)
language plpgsql
security definer
set search_path = public, auth, pg_temp
as $$
begin
  if auth.uid() is null or not public.current_user_is_staff() then
    raise exception 'STAFF_REQUIRED';
  end if;

  return query
  select
    sv.id,
    sv.version_no,
    sv.source_action,
    sv.source_entity_type,
    sv.source_entity_id,
    sv.actor_user_id,
    coalesce(u.email, 'System')::text as actor_label,
    sv.metadata,
    coalesce((
      select count(*)::integer
      from jsonb_array_elements(coalesce(sv.snapshot->'schedule_master', '[]'::jsonb)) x
      where coalesce((x->>'is_active')::boolean, true) = true
        and (x->>'deleted_at' is null or x->>'deleted_at' = '')
    ), 0)::integer as master_count,
    coalesce((
      select count(*)::integer
      from jsonb_array_elements(coalesce(sv.snapshot->'schedule_incidentals', '[]'::jsonb)) x
      where x->>'deleted_at' is null or x->>'deleted_at' = ''
    ), 0)::integer as active_incidental_count,
    coalesce((
      select count(*)::integer
      from jsonb_array_elements(coalesce(sv.snapshot->'academic_events', '[]'::jsonb)) x
      where upper(coalesce(x->>'status', 'ACTIVE')) = 'ACTIVE'
    ), 0)::integer as active_calendar_count,
    sv.created_at
  from public.schedule_versions sv
  left join auth.users u on u.id = sv.actor_user_id
  order by sv.version_no desc
  limit greatest(1, least(coalesce(p_limit, 50), 200));
end;
$$;

revoke all on function public.ejadwal_list_schedule_versions_v1(integer) from public;
grant execute on function public.ejadwal_list_schedule_versions_v1(integer) to authenticated;

create or replace function public.ejadwal_rollback_schedule_version_v1(
  p_version_id uuid,
  p_reason text default null
)
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_actor uuid := auth.uid();
  v_snapshot jsonb;
  v_target_no bigint;
  v_before_version uuid;
  v_before_no bigint;
  v_master_count integer := 0;
  v_incidental_count integer := 0;
  v_calendar_count integer := 0;
  r record;
begin
  if v_actor is null or not public.current_user_has_role('ADMIN') then
    raise exception 'ADMIN_REQUIRED';
  end if;

  select sv.snapshot, sv.version_no
    into v_snapshot, v_target_no
  from public.schedule_versions sv
  where sv.id = p_version_id;

  if v_snapshot is null then
    raise exception 'SCHEDULE_VERSION_NOT_FOUND';
  end if;

  select sv.id, sv.version_no
    into v_before_version, v_before_no
  from public.schedule_versions sv
  order by sv.version_no desc
  limit 1;

  perform set_config('ejadwal.rollback_mode', 'on', true);

  -- Rows created after the target version are retained historically but disabled.
  update public.schedule_master sm
     set is_active = false,
         deleted_at = coalesce(sm.deleted_at, now()),
         deleted_by = coalesce(sm.deleted_by, v_actor),
         updated_at = now()
   where not exists (
     select 1
     from jsonb_array_elements(coalesce(v_snapshot->'schedule_master', '[]'::jsonb)) x
     where (x->>'id')::uuid = sm.id
   );

  for r in
    select * from jsonb_to_recordset(coalesce(v_snapshot->'schedule_master', '[]'::jsonb)) as x(
      id uuid,
      class_id uuid,
      day_of_week smallint,
      period smallint,
      start_time time without time zone,
      end_time time without time zone,
      subject text,
      room_id text,
      is_combined boolean,
      other_teachers_supervise boolean,
      special_note text,
      is_active boolean,
      legacy_row_id text,
      created_at timestamptz,
      updated_at timestamptz,
      deleted_at timestamptz,
      deleted_by uuid,
      class_mode text
    )
  loop
    insert into public.schedule_master(
      id, class_id, day_of_week, period, start_time, end_time, subject, room_id,
      is_combined, other_teachers_supervise, special_note, is_active, legacy_row_id,
      created_at, updated_at, deleted_at, deleted_by, class_mode
    ) values (
      r.id, r.class_id, r.day_of_week, r.period, r.start_time, r.end_time, r.subject, r.room_id,
      coalesce(r.is_combined, false), coalesce(r.other_teachers_supervise, false), r.special_note,
      coalesce(r.is_active, true), r.legacy_row_id, coalesce(r.created_at, now()), now(),
      r.deleted_at, r.deleted_by, coalesce(r.class_mode, case when r.is_combined then 'COMBINED' else 'NORMAL' end)
    )
    on conflict (id) do update
      set class_id = excluded.class_id,
          day_of_week = excluded.day_of_week,
          period = excluded.period,
          start_time = excluded.start_time,
          end_time = excluded.end_time,
          subject = excluded.subject,
          room_id = excluded.room_id,
          is_combined = excluded.is_combined,
          other_teachers_supervise = excluded.other_teachers_supervise,
          special_note = excluded.special_note,
          is_active = excluded.is_active,
          legacy_row_id = excluded.legacy_row_id,
          updated_at = now(),
          deleted_at = excluded.deleted_at,
          deleted_by = excluded.deleted_by,
          class_mode = excluded.class_mode;
    v_master_count := v_master_count + 1;
  end loop;

  delete from public.schedule_master_teachers;
  insert into public.schedule_master_teachers(schedule_id, position, teacher_id, teacher_name_snapshot, created_at)
  select schedule_id, position, teacher_id, coalesce(teacher_name_snapshot, ''), coalesce(created_at, now())
  from jsonb_to_recordset(coalesce(v_snapshot->'schedule_master_teachers', '[]'::jsonb)) as x(
    schedule_id uuid,
    position smallint,
    teacher_id uuid,
    teacher_name_snapshot text,
    created_at timestamptz
  );

  update public.schedule_incidentals si
     set deleted_at = coalesce(si.deleted_at, now()),
         deleted_by = coalesce(si.deleted_by, v_actor),
         updated_at = now()
   where not exists (
     select 1
     from jsonb_array_elements(coalesce(v_snapshot->'schedule_incidentals', '[]'::jsonb)) x
     where (x->>'id')::uuid = si.id
   );

  for r in
    select * from jsonb_to_recordset(coalesce(v_snapshot->'schedule_incidentals', '[]'::jsonb)) as x(
      id uuid,
      schedule_date date,
      class_id uuid,
      period smallint,
      kind text,
      override_subject text,
      override_room_id text,
      override_is_combined boolean,
      override_special_note text,
      reason text,
      incidental_type text,
      legacy_row_id text,
      created_at timestamptz,
      updated_at timestamptz,
      deleted_at timestamptz,
      deleted_by uuid,
      override_class_mode text
    )
  loop
    insert into public.schedule_incidentals(
      id, schedule_date, class_id, period, kind, override_subject, override_room_id,
      override_is_combined, override_special_note, reason, incidental_type, legacy_row_id,
      created_at, updated_at, deleted_at, deleted_by, override_class_mode
    ) values (
      r.id, r.schedule_date, r.class_id, r.period, coalesce(r.kind, 'OVERRIDE'), r.override_subject,
      r.override_room_id, r.override_is_combined, r.override_special_note, r.reason, r.incidental_type,
      r.legacy_row_id, coalesce(r.created_at, now()), now(), r.deleted_at, r.deleted_by, r.override_class_mode
    )
    on conflict (id) do update
      set schedule_date = excluded.schedule_date,
          class_id = excluded.class_id,
          period = excluded.period,
          kind = excluded.kind,
          override_subject = excluded.override_subject,
          override_room_id = excluded.override_room_id,
          override_is_combined = excluded.override_is_combined,
          override_special_note = excluded.override_special_note,
          reason = excluded.reason,
          incidental_type = excluded.incidental_type,
          legacy_row_id = excluded.legacy_row_id,
          updated_at = now(),
          deleted_at = excluded.deleted_at,
          deleted_by = excluded.deleted_by,
          override_class_mode = excluded.override_class_mode;
    v_incidental_count := v_incidental_count + 1;
  end loop;

  delete from public.schedule_incidental_teacher_overrides;
  insert into public.schedule_incidental_teacher_overrides(
    incidental_id, position, action, teacher_id, teacher_name_snapshot, created_at
  )
  select incidental_id, position, coalesce(action, 'SET'), teacher_id, teacher_name_snapshot, coalesce(created_at, now())
  from jsonb_to_recordset(coalesce(v_snapshot->'schedule_incidental_teacher_overrides', '[]'::jsonb)) as x(
    incidental_id uuid,
    position smallint,
    action text,
    teacher_id uuid,
    teacher_name_snapshot text,
    created_at timestamptz
  );

  delete from public.academic_events ae
   where not exists (
     select 1
     from jsonb_array_elements(coalesce(v_snapshot->'academic_events', '[]'::jsonb)) x
     where (x->>'id')::uuid = ae.id
   );

  for r in
    select * from jsonb_to_recordset(coalesce(v_snapshot->'academic_events', '[]'::jsonb)) as x(
      id uuid,
      legacy_event_code text,
      date_start date,
      date_end date,
      event_name text,
      event_type text,
      scope text,
      class_id uuid,
      period_start smallint,
      period_end smallint,
      status text,
      created_at timestamptz,
      updated_at timestamptz,
      admin_group_code text
    )
  loop
    insert into public.academic_events(
      id, legacy_event_code, date_start, date_end, event_name, event_type, scope, class_id,
      period_start, period_end, status, created_at, updated_at, admin_group_code
    ) values (
      r.id, r.legacy_event_code, r.date_start, r.date_end, r.event_name, r.event_type,
      coalesce(r.scope, 'ALL'), r.class_id, r.period_start, r.period_end, coalesce(r.status, 'ACTIVE'),
      coalesce(r.created_at, now()), now(), r.admin_group_code
    )
    on conflict (id) do update
      set legacy_event_code = excluded.legacy_event_code,
          date_start = excluded.date_start,
          date_end = excluded.date_end,
          event_name = excluded.event_name,
          event_type = excluded.event_type,
          scope = excluded.scope,
          class_id = excluded.class_id,
          period_start = excluded.period_start,
          period_end = excluded.period_end,
          status = excluded.status,
          updated_at = now(),
          admin_group_code = excluded.admin_group_code;
    v_calendar_count := v_calendar_count + 1;
  end loop;

  perform set_config('ejadwal.rollback_mode', 'off', true);

  insert into public.audit_logs(actor_user_id, action, entity_type, entity_id, before_data, after_data)
  values (
    v_actor,
    'SCHEDULE_VERSION_ROLLBACK',
    'SCHEDULE_VERSION',
    p_version_id::text,
    jsonb_build_object('previous_version_id', v_before_version, 'previous_version_no', v_before_no),
    jsonb_build_object(
      'rolled_back_to_version_id', p_version_id,
      'rolled_back_to_version_no', v_target_no,
      'reason', nullif(trim(coalesce(p_reason, '')), ''),
      'master_rows_restored', v_master_count,
      'incidentals_restored', v_incidental_count,
      'academic_events_restored', v_calendar_count
    )
  );

  return jsonb_build_object(
    'rolled_back_to_version_id', p_version_id,
    'rolled_back_to_version_no', v_target_no,
    'master_rows_restored', v_master_count,
    'incidentals_restored', v_incidental_count,
    'academic_events_restored', v_calendar_count
  );
end;
$$;

revoke all on function public.ejadwal_rollback_schedule_version_v1(uuid,text) from public;
grant execute on function public.ejadwal_rollback_schedule_version_v1(uuid,text) to authenticated;

-- Baseline: history before V3.13.6 is summarized as the state existing at migration time.
insert into public.schedule_versions(
  txid, source_action, source_entity_type, source_entity_id, actor_user_id, metadata, snapshot, created_at
)
select
  txid_current(),
  'VERSIONING_BASELINE',
  'SCHEDULE_STATE',
  'v3.13.6-baseline',
  auth.uid(),
  jsonb_build_object('note', 'Baseline state captured when V3.13.6 schedule versioning was enabled.'),
  public.ejadwal_schedule_snapshot_v1(),
  now()
where not exists (
  select 1 from public.schedule_versions where source_action = 'VERSIONING_BASELINE'
)
on conflict (txid) do nothing;

commit;
